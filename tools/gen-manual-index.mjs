// Builds data/manual-index.json (OEM manual links by model key) from the Model Manual Index CSV.
// Usage: node tools/gen-manual-index.mjs [index-results.csv] [--out data/manual-index.json] [--dropped-md dropped.md]
//   Default CSV: /workspace/hvac-library-index/index-results.csv
// Rules: keep a row only when Official URL is set AND Status is one of KEEP_STATUSES. Every other status
// (NOT FOUND, LOGIN-ONLY, DUPLICATE, NOT OEM) is dropped. Filename, Library folder and Notes are never copied.
// A kept URL that is not https:// or is on shareddocs.com / manualslib is FATAL (nonzero exit).
// A kept URL that is not on the allowlist (tools/official-domains.js) is DROPPED and listed; the allowlist is not edited here.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { isOfficialUrl, isExcluded } from "./official-domains.js";
import { NON_OEM_HOSTS } from "./manual-match.js";

export const DEFAULT_CSV = "/workspace/hvac-library-index/index-results.csv";
export const KEEP_STATUSES = ["MATCHED", "MATCHED (newer rev)", "MATCHED (newer edition)", "RELATED", "REFERENCE"];
const COLS = { brand: "Brand", model: "Model/series", key: "Match key", title: "Doc title/number", status: "Status", url: "Official URL", date: "Verified date" };

/** RFC 4180-style CSV (quoted fields, "" escapes, CRLF or LF). */
export function parseCsv(text) {
  const rows = []; let row = [], f = "", q = false;
  const t = String(text).replace(/^\uFEFF/, "");
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"') { if (t[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(f); f = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && t[i + 1] === "\n") i++; row.push(f); rows.push(row); row = []; f = ""; }
    else f += c;
  }
  if (f !== "" || row.length) { row.push(f); rows.push(row); }
  return rows.filter((r) => r.some((x) => x.trim() !== ""));
}

const hostOf = (url) => { try { return new URL(url).hostname.toLowerCase(); } catch (e) { return ""; } };
const BANNED = (h) => h === "shareddocs.com" || h.endsWith(".shareddocs.com") || /(^|\.)manualslib\.[a-z.]+$/.test(h) || h.includes("manualslib");

/** Pure build: { entries, dropped, fatal, counts }. */
export function buildManualIndex(csvText) {
  const [head, ...body] = parseCsv(csvText);
  const ix = {};
  for (const [k, name] of Object.entries(COLS)) {
    ix[k] = head.findIndex((h) => h.trim() === name);
    if (ix[k] < 0) throw new Error("CSV is missing column: " + name);
  }
  const cell = (r, k) => (r[ix[k]] || "").trim();
  const entries = [], dropped = [], fatal = [];
  let kept = 0;
  for (const r of body) {
    const url = cell(r, "url"), status = cell(r, "status");
    if (!url || !KEEP_STATUSES.includes(status)) continue;
    kept++;
    const host = hostOf(url);
    const row = { brand: cell(r, "brand"), model: cell(r, "model"), host, url };
    if (!/^https:\/\//i.test(url) || !host) { fatal.push({ ...row, why: "not https://" }); continue; }
    if (BANNED(host)) { fatal.push({ ...row, why: "shareddocs/manualslib host" }); continue; }
    if (!isOfficialUrl(url) || isExcluded(url)) { dropped.push(row); continue; }
    entries.push({
      brand: row.brand,
      model: row.model,
      matchKeys: cell(r, "key").split(";").map((s) => s.trim()).filter(Boolean),
      docTitle: cell(r, "title"),
      status,
      url,
      verifiedDate: cell(r, "date"),
      nonOem: NON_OEM_HOSTS.includes(host),
    });
  }
  return { entries, dropped, fatal, counts: { rows: body.length, kept, written: entries.length, dropped: dropped.length } };
}

const mdCell = (s) => String(s).replace(/\|/g, "\\|");
export function droppedMarkdown(dropped) {
  return ["| Brand | Model | Host | URL |", "|---|---|---|---|", ...dropped.map((d) => "| " + [d.brand, d.model, d.host, d.url].map(mdCell).join(" | ") + " |")].join("\n") + "\n";
}

function main(argv) {
  const args = [...argv]; let out = fileURLToPath(new URL("../data/manual-index.json", import.meta.url)), md = null;
  const oi = args.indexOf("--out"); if (oi >= 0) { out = args[oi + 1]; args.splice(oi, 2); }
  const mi = args.indexOf("--dropped-md"); if (mi >= 0) { md = args[mi + 1]; args.splice(mi, 2); }
  const csv = args[0] || DEFAULT_CSV;
  const res = buildManualIndex(readFileSync(csv, "utf8"));
  if (res.fatal.length) {
    for (const f of res.fatal) console.error("FATAL: " + f.why + ": " + f.brand + " / " + f.model + " -> " + f.url);
    process.exit(1);
  }
  const data = {
    about: "OEM manual links by model key, generated by tools/gen-manual-index.mjs from the Model Manual Index (index-results.csv). Official URLs on the allowlist only. Educational only — verify with OEM.",
    entries: res.entries,
  };
  writeFileSync(out, JSON.stringify(data, null, 1) + "\n");
  console.log("Rows " + res.counts.rows + ", kept " + res.counts.kept + ", written " + res.counts.written + ", dropped (not on allowlist) " + res.counts.dropped + " -> " + out);
  if (res.dropped.length) { console.log("Dropped (not on allowlist):"); console.log(droppedMarkdown(res.dropped)); }
  if (md) writeFileSync(md, droppedMarkdown(res.dropped));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
